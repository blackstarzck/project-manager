const versionButton = (page: Page, project: Project, id: string) => {
  const group = project.flowGroups.find(group => group.versions.some(version => version.id === id))!;
  const version = group.versions.find(version => version.id === id)!;
  return page.getByRole('button', { name: `${group.name} / ${version.name} 선택`, exact: true });
};

test('V01/V05: switching immediately after typing flushes only the original version and persists selected version', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  let project = await addFlowVersion(request, original, { copy: true });
  const secondId = project.selectedFlowVersionId!;
  project = await selectFlowVersion(request, project, original.selectedFlowVersionId!);
  await page.goto(`/#project/${project.id}`);
  await page.getByRole('tab', { name: '유저플로우', exact: true }).click();
  await page.locator('.react-flow__node').filter({ hasText: '도서 검색' }).click();
  await page.getByRole('textbox', { name: '노드 이름', exact: true }).fill('전환 직전 입력한 원본 검색');
  await versionButton(page, project, secondId).click();
  await expect(versionButton(page, project, secondId)).toHaveAttribute('aria-pressed', 'true');
  const current = await getProject(request, project.id);
  expect(current.flow.nodes[1].label).toBe(original.flow.nodes[1].label);
  expect(current.flowGroups[0].versions.find(version => version.id === original.selectedFlowVersionId)!.flow.nodes[1].label).toBe('전환 직전 입력한 원본 검색');
  expect(current.flowGroups[0].versions.find(version => version.id === original.selectedFlowVersionId)!.wireframes).toEqual(original.wireframes);
  await page.reload();
  await page.getByRole('tab', { name: '유저플로우', exact: true }).click();
  await expect(versionButton(page, project, secondId)).toHaveAttribute('aria-pressed', 'true');
  await versionButton(page, project, original.selectedFlowVersionId!).click();
  await expect(page.locator('.react-flow__node').filter({ hasText: '전환 직전 입력한 원본 검색' })).toBeVisible();
  await page.screenshot({ path: 'tests/artifacts/phase2-flow-versions.png', fullPage: true });
});

test('V05: failed save prevents a version switch and retains the unsaved draft for retry', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  let project = await addFlowVersion(request, original, { copy: true });
  const secondId = project.selectedFlowVersionId!;
  project = await selectFlowVersion(request, project, original.selectedFlowVersionId!);
  await page.goto(`/#project/${project.id}`);
  await page.getByRole('tab', { name: '유저플로우', exact: true }).click();
  await page.locator('.react-flow__node').filter({ hasText: '도서 검색' }).click();
  const saveRoute = `**/api/projects/${project.id}/artifacts/flow`;
  await page.route(saveRoute, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 'QA_SAVE_FAILED', message: '검수용 일시적 저장 실패' }) }));
  await page.getByRole('textbox', { name: '노드 이름', exact: true }).fill('저장 실패에도 보존할 변경');
  await versionButton(page, project, secondId).click();
  await expect(page.getByRole('button', { name: '저장 재시도', exact: true })).toBeVisible();
  await expect(versionButton(page, project, original.selectedFlowVersionId!)).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('textbox', { name: '노드 이름', exact: true })).toHaveValue('저장 실패에도 보존할 변경');
  expect((await getProject(request, project.id)).selectedFlowVersionId).toBe(original.selectedFlowVersionId);
  await page.unroute(saveRoute);
  await versionButton(page, project, secondId).click();
  await expect(versionButton(page, project, secondId)).toHaveAttribute('aria-pressed', 'true');
  const saved = await getProject(request, project.id);
  expect(saved.flowGroups[0].versions.find(version => version.id === original.selectedFlowVersionId)!.flow.nodes[1].label).toBe('저장 실패에도 보존할 변경');
});

test('V01: user can create a blank flow group and copy a version without losing existing screens', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  await page.goto(`/#project/${original.id}`);
  await page.getByRole('tab', { name: '유저플로우', exact: true }).click();
  await page.getByRole('button', { name: '현재 버전 복제', exact: true }).click();
  const copy = page.getByRole('dialog', { name: '현재 버전 복제', exact: true });
  await copy.getByRole('textbox', { name: '버전 이름', exact: true }).fill('검수용 개선 버전');
  await copy.getByRole('button', { name: '현재 버전 복제', exact: true }).click();
  await expect(copy).toHaveCount(0);
  let project = await getProject(request, original.id);
  expect(project.flowGroups[0].versions).toHaveLength(2);
  expect(project.wireframes).toEqual(original.wireframes);
  await page.getByRole('button', { name: '새 유저플로우', exact: true }).click();
  const create = page.getByRole('dialog', { name: '새 유저플로우', exact: true });
  await create.getByRole('textbox', { name: '플로우 이름', exact: true }).fill('사서 관리 흐름');
  await create.getByRole('button', { name: '플로우 만들기', exact: true }).click();
  await expect(create).toHaveCount(0);
  project = await getProject(request, project.id);
  expect(project.flowGroups).toHaveLength(2);
  expect(project.flow.nodes).toHaveLength(0);
  expect(project.wireframes).toHaveLength(0);
  await versionButton(page, project, original.selectedFlowVersionId!).click();
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  await expect(page.getByTestId(`screen-${original.wireframes[0].id}`)).toBeVisible();
  expect((await getProject(request, project.id)).wireframes).toEqual(original.wireframes);
});

