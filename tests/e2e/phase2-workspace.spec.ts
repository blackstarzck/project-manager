test('N04: unlinking and deleting nested targets remains saveable and undo never revives dangling links', async ({ page, request }) => {
  const project = await seedNestedProject(request);
  await page.goto(`/#project/${project.id}`);
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  const element = async (key: string) => flattenElements((await getProject(request, project.id)).wireframes[0].elements).find(item => item.id === `${project.id}-nested-${key}`);
  await page.getByTestId(`layer-${project.id}-nested-nested-link`).click();
  await page.getByRole('combobox', { name: '이동 대상 화면', exact: true }).selectOption('');
  await expect.poll(async () => (await element('nested-link'))?.targetScreenId).toBeNull();
  expect((await element('nested-link'))?.action).not.toBe('navigate');
  await page.getByRole('button', { name: '화면 편집 실행 취소', exact: true }).click();
  await expect.poll(async () => (await element('nested-link'))?.targetScreenId).toBe(project.wireframes[1].id);
  await page.getByTestId(`layer-${project.id}-nested-modal`).click();
  await page.getByRole('button', { name: '요소와 하위 요소 삭제', exact: true }).click();
  await expect.poll(async () => !!await element('modal')).toBeFalsy();
  expect((await element('open'))?.targetElementId).toBeNull();
  expect((await element('open'))?.action).not.toBe('openModal');
  await page.getByRole('button', { name: '화면 편집 실행 취소', exact: true }).click();
  await expect.poll(async () => (await element('open'))?.targetElementId).toBe(`${project.id}-nested-modal`);
  await page.getByTestId(`screen-${project.wireframes[1].id}`).click();
  await page.getByRole('button', { name: '화면 삭제', exact: true }).click();
  await expect.poll(async () => (await getProject(request, project.id)).wireframes.length).toBe(1);
  const undo = page.getByRole('button', { name: '화면 편집 실행 취소', exact: true });
  if (await undo.isEnabled()) await undo.click();
  await expect(page.getByRole('status').filter({ hasText: '모든 변경 저장됨' })).toBeVisible();
  const current = await getProject(request, project.id);
  const ids = new Set(current.wireframes.map(screen => screen.id));
  for (const screen of current.wireframes) for (const node of flattenElements(screen.elements)) {
    if (node.targetScreenId) expect(ids.has(node.targetScreenId)).toBeTruthy();
    if (node.action === 'navigate') expect(node.targetScreenId).toBeTruthy();
  }
  await page.reload();
  expect((await getProject(request, project.id)).wireframes).toEqual(current.wireframes);
});

test('V06/N04: switching through an old AI proposal resets wireframe undo despite shared screen IDs', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  const response = await request.post(`${API}/projects/${original.id}/ai/runs`, { headers: mutationHeaders, data: { artifact: 'wireframes', prompt: '원본 화면 제목 개선', entityIds: [original.wireframes[0].id], flowVersionId: original.selectedFlowVersionId } });
  expect(response.status()).toBe(202);
  let run: AiRun = await response.json();
  await expect.poll(async () => { run = await (await request.get(`${API}/ai/runs/${run.id}`)).json(); return run.status; }).toBe('succeeded');
  const copied = await addFlowVersion(request, original, { copy: true });
  await page.goto(`/#project/${original.id}`);
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  await page.getByTestId(`layer-${original.id}-nested-nested-title`).click();
  await page.getByRole('textbox', { name: '요소 내용', exact: true }).fill('복제 버전에서 작성한 독립 제목');
  await expect.poll(async () => JSON.stringify((await getProject(request, original.id)).wireframes)).toContain('복제 버전에서 작성한 독립 제목');
  await expect(page.getByRole('button', { name: '화면 편집 실행 취소', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'AI 도우미 열기', exact: true }).click();
  await page.getByRole('button', { name: '원래 와이어프레임 버전으로 전환', exact: true }).click();
  await expect.poll(async () => (await getProject(request, original.id)).selectedFlowVersionId).toBe(original.selectedFlowVersionId);
  await expect.poll(async () => (await getProject(request, original.id)).selectedWireframeVersionId).toBe(original.selectedWireframeVersionId);
  await expect(page.getByRole('button', { name: '화면 편집 실행 취소', exact: true })).toBeDisabled();
  const current = await getProject(request, original.id);
  expect(current.wireframes).toEqual(original.wireframes);
  expect(JSON.stringify(current.flowGroups.flatMap(group => group.versions).find(version => version.id === copied.selectedFlowVersionId)!.wireframes)).toContain('복제 버전에서 작성한 독립 제목');
  await page.getByRole('button', { name: '변경 제안 검토', exact: true }).click();
  await page.getByRole('button', { name: '선택 승인', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const approved = await getProject(request, original.id);
  expect(approved.wireframes[0].elements[0].text).toBe('AI가 수정한 화면 제목');
  expect(JSON.stringify(approved.flowGroups.flatMap(group => group.versions).find(version => version.id === copied.selectedFlowVersionId)!.wireframes)).toContain('복제 버전에서 작성한 독립 제목');
});
