import { expect, test } from '@playwright/test';
import { API, mutationHeaders, saveArtifact } from '../fixtures.js';
import { addFlowVersion, getProject, seedNestedProject } from '../phase2-fixtures.js';
import { activeFlow, activeWire, addWireVersion, awaitRun, selectWireVersion, wireRun } from '../phase4-fixtures.js';

test('WU01: manual screen copy flushes edits, rename persists, and switching resets undo while preserving versions', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  await page.goto(`/#project/${original.id}`);
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  await page.getByTestId(`layer-${original.id}-nested-nested-title`).click();
  await page.getByRole('textbox', { name: '요소 내용', exact: true }).fill('복제 직전에 저장할 제목');
  await page.getByRole('button', { name: '화면 버전 복제', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '와이어프레임 버전 복제', exact: true });
  await dialog.getByRole('textbox', { name: '화면 버전 이름', exact: true }).fill('모바일 검토용 사본');
  await dialog.getByRole('button', { name: '화면 버전 복제', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  let saved = await getProject(request, original.id);
  const copyId = saved.selectedWireframeVersionId!;
  expect(copyId).not.toBe(original.selectedWireframeVersionId);
  expect(JSON.stringify(activeWire(saved).wireframes)).toContain('복제 직전에 저장할 제목');
  expect(activeFlow(saved).wireframeVersions[0].wireframes).toEqual(saved.wireframes);
  await page.getByRole('button', { name: '화면 버전 이름 변경', exact: true }).click();
  const rename = page.getByRole('dialog', { name: '화면 버전 이름 변경', exact: true });
  await rename.getByRole('textbox', { name: '화면 버전 이름', exact: true }).fill('검토 완료 화면');
  await rename.getByRole('button', { name: '이름 저장', exact: true }).click();
  await expect(rename).toHaveCount(0);
  await page.getByTestId(`layer-${original.id}-nested-nested-title`).click();
  await page.getByRole('textbox', { name: '요소 내용', exact: true }).fill('사본에서만 바꾼 제목');
  const selector = page.getByRole('combobox', { name: '와이어프레임 버전 선택', exact: true });
  await selector.selectOption(original.selectedWireframeVersionId!);
  await expect(selector).toHaveValue(original.selectedWireframeVersionId!);
  await expect(page.getByTestId(`wire-element-${original.id}-nested-nested-title`)).toContainText('복제 직전에 저장할 제목');
  await expect(page.getByRole('button', { name: '화면 편집 실행 취소', exact: true })).toBeDisabled();
  await selector.selectOption(copyId);
  await expect(page.getByTestId(`wire-element-${original.id}-nested-nested-title`)).toContainText('사본에서만 바꾼 제목');
  await page.reload();
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  await expect(selector).toHaveValue(copyId);
  saved = await getProject(request, original.id);
  expect(activeWire(saved).name).toBe('검토 완료 화면');
  await page.screenshot({ path: 'tests/artifacts/phase4-wireframe-versions.png', fullPage: true });
  await page.getByRole('button', { name: '내보내기', exact: true }).click();
  const exported = page.waitForRequest(req => req.url().includes('/export?') && req.url().includes('format=html'));
  const download = page.waitForEvent('download');
  await page.getByRole('dialog', { name: '내보내기 및 백업', exact: true }).getByRole('button', { name: /^HTML/ }).click();
  const url = new URL((await exported).url());
  expect(url.searchParams.get('flowVersionId')).toBe(saved.selectedFlowVersionId);
  expect(url.searchParams.get('wireframeVersionId')).toBe(copyId);
  await (await download).saveAs('tests/artifacts/phase4-selected-version.html');
});

test('WU02: failed autosave prevents screen-version switch and retains the editable source draft', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  let project = await addWireVersion(request, original);
  const copyId = project.selectedWireframeVersionId!;
  project = await selectWireVersion(request, project, original.selectedWireframeVersionId!);
  await page.goto(`/#project/${project.id}`);
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  const selector = page.getByRole('combobox', { name: '와이어프레임 버전 선택', exact: true });
  const route = `**/api/projects/${project.id}/artifacts/wireframes`;
  await page.route(route, intercepted => intercepted.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 'QA_SAVE_FAILED', message: '화면 버전 전환 저장 실패' }) }));
  await page.getByTestId(`layer-${project.id}-nested-nested-title`).click();
  await page.getByRole('textbox', { name: '요소 내용', exact: true }).fill('실패해도 원본에 남을 초안');
  await selector.selectOption(copyId);
  await expect(page.getByRole('button', { name: '저장 재시도', exact: true })).toBeVisible();
  await expect(selector).toHaveValue(original.selectedWireframeVersionId!);
  await expect(page.getByRole('textbox', { name: '요소 내용', exact: true })).toHaveValue('실패해도 원본에 남을 초안');
  expect(await getProject(request, project.id)).toEqual(project);
  await page.unroute(route);
  await selector.selectOption(copyId);
  await expect(selector).toHaveValue(copyId);
  const saved = await getProject(request, project.id);
  expect(saved.wireframes).toEqual(original.wireframes);
  expect(JSON.stringify(activeFlow(saved).wireframeVersions.find(version => version.id === original.selectedWireframeVersionId)!.wireframes)).toContain('실패해도 원본에 남을 초안');
});

test('WU03: regeneration retry preserves screen mode and dual context; result navigation atomically selects owning flow and screen version', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  const run = await awaitRun(request, await wireRun(request, original, 'regenerate', '선택 화면 새 버전 생성', [original.wireframes[0].id]));
  const changed = await saveArtifact(request, original, 'wireframes', original.wireframes.map((screen, index) => index === 0 ? { ...screen, name: '수동 변경 원본 화면' } : screen));
  const conflict = await request.post(`${API}/proposals/${run.proposalId}/resolve`, { headers: mutationHeaders, data: { action: 'approve', commandId: crypto.randomUUID() } });
  expect(conflict.status()).toBe(409);
  await page.goto(`/#project/${original.id}`);
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  await page.getByRole('button', { name: 'AI 도우미 열기', exact: true }).click();
  await expect(page.getByRole('combobox', { name: '와이어프레임 생성 방식', exact: true })).toHaveValue('edit');
  const started = page.waitForRequest(req => req.method() === 'POST' && req.url().endsWith(`/api/projects/${original.id}/ai/runs`));
  await page.getByRole('button', { name: '전체 요청으로 새로 생성', exact: true }).click();
  expect((await started).postDataJSON()).toMatchObject({ wireframeGenerationMode: 'regenerate', flowVersionId: original.selectedFlowVersionId, wireframeVersionId: original.selectedWireframeVersionId, entityIds: [original.wireframes[0].id] });
  await page.getByRole('button', { name: '변경 제안 검토', exact: true }).click();
  expect(await getProject(request, original.id)).toEqual(changed);
  await page.getByRole('button', { name: '선택 승인', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const generated = await getProject(request, original.id);
  expect(generated.selectedWireframeVersionId).not.toBe(original.selectedWireframeVersionId);
  expect(activeFlow(generated).wireframeVersions[0]).toEqual(activeWire(changed));
  const otherFlow = await addFlowVersion(request, generated, { copy: true, name: '다른 플로우 문맥' });
  await page.reload();
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  if (!(await page.getByRole('button', { name: '생성된 와이어프레임 보기', exact: true }).isVisible())) await page.getByRole('button', { name: 'AI 도우미 열기', exact: true }).click();
  await page.getByRole('button', { name: '생성된 와이어프레임 보기', exact: true }).click();
  await expect(page.getByRole('combobox', { name: '와이어프레임 플로우 버전 선택', exact: true })).toHaveValue(original.selectedFlowVersionId!);
  await expect(page.getByRole('combobox', { name: '와이어프레임 버전 선택', exact: true })).toHaveValue(generated.selectedWireframeVersionId!);
  const final = await getProject(request, original.id);
  expect(final.selectedFlowVersionId).not.toBe(otherFlow.selectedFlowVersionId);
  expect(final.wireframes).toEqual(generated.wireframes);
});

test('WS01: incremental valid screen receipt is visible while running and never applies partial data', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  await page.goto(`/#project/${original.id}`);
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  // The generation dialog opens the AI panel when submitting; keep its toolbar unobscured.
  await page.getByRole('button', { name: '전체 화면 개선', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '와이어프레임 생성 대상 선택', exact: true });
  await expect(dialog.getByRole('checkbox', { name: '새 화면 버전으로 만들기', exact: true })).toBeChecked();
  // Raw JSON receipts remain an edit-mode contract; version generation now has validated page jobs.
  await dialog.getByRole('checkbox', { name: '새 화면 버전으로 만들기', exact: true }).uncheck();
  await dialog.getByRole('textbox', { name: '화면 생성 추가 요청', exact: true }).fill('[QA_STREAM_SCREENS] 화면 두 개 점진 수신');
  const started = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`/api/projects/${original.id}/ai/runs`));
  await dialog.getByRole('button', { name: '선택한 화면 생성 요청', exact: true }).click();
  const run = await (await started).json();
  expect(run.wireframeGenerationMode).toBe('edit');
  await expect(page.getByText('화면 데이터 수신 1개 · 요청 대상 2개', { exact: true })).toBeVisible();
  const processing = await (await request.get(`${API}/ai/runs/${run.id}`)).json();
  expect(processing.status).toBe('running');
  expect(processing.proposalId).toBeNull();
  expect(await getProject(request, original.id)).toEqual(original);
  await page.screenshot({ path: 'tests/artifacts/phase4-streaming-receipt.png', fullPage: true });
  const completed = await awaitRun(request, run);
  expect(completed.proposalId).toBeTruthy();
  expect(await getProject(request, original.id)).toEqual(original);
});
