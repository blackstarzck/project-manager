test('UXE04: flow action menus support keyboard focus and keep copy dialogs open while a version is saving', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  const group = original.flowGroups.find(item => item.versions.some(version => version.id === original.selectedFlowVersionId))!;
  const version = group.versions.find(item => item.id === original.selectedFlowVersionId)!;
  await page.goto(`/#project/${original.id}/flow`);
  await page.setViewportSize({ width: 970, height: 760 });
  await page.getByRole('button', { name: '플로우 목록 표시', exact: true }).click();
  const groupTrigger = page.getByRole('button', { name: `${group.name} 그룹 메뉴`, exact: true });
  await groupTrigger.focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('menuitem', { name: '이름 변경', exact: true })).toBeFocused();
  await page.keyboard.press('ArrowDown');
  await expect(page.getByRole('menuitem', { name: '새 그룹으로 분기', exact: true })).toBeFocused();
  await page.keyboard.press('Escape'); await expect(groupTrigger).toBeFocused();
  await expect(page.getByRole('complementary', { name: '플로우 목록', exact: true })).toBeVisible();
  await groupTrigger.press('Enter');
  await page.getByRole('menuitem', { name: '이름 변경', exact: true }).click();
  const rename = page.getByRole('dialog', { name: '이름 변경', exact: true });
  await expect(rename).toBeVisible(); await rename.press('Escape');
  await expect(rename).toHaveCount(0); await expect(groupTrigger).toBeFocused();
  await page.getByRole('button', { name: `${version.name} 버전 메뉴`, exact: true }).press('Enter');
  await page.getByRole('menuitem', { name: '현재 버전 복제', exact: true }).click();
  const copy = page.getByRole('dialog', { name: '현재 버전 복제', exact: true });
  await copy.getByRole('textbox', { name: '버전 이름', exact: true }).fill('키보드 검토 사본');
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  await page.route(`**/api/projects/${original.id}/flow-groups/*/versions`, async route => { await gate; await route.continue(); });
  await copy.getByRole('button', { name: '현재 버전 복제', exact: true }).click();
  await expect(copy).toHaveAttribute('aria-busy', 'true');
  await expect(copy.getByRole('button', { name: '닫기', exact: true })).toBeDisabled();
  await expect(copy.getByRole('textbox', { name: '버전 이름', exact: true })).toBeDisabled();
  await page.keyboard.press('Escape'); await expect(copy).toBeVisible();
  release();
  await expect(copy).toHaveCount(0);
  await page.getByRole('button', { name: '플로우 목록 표시', exact: true }).click();
  await expect(page.getByRole('button', { name: `${group.name} / 키보드 검토 사본 선택`, exact: true })).toHaveAttribute('aria-pressed', 'true');
  const saved = await getProject(request, original.id);
  expect(saved.selectedFlowVersionId).not.toBe(original.selectedFlowVersionId);
  expect(saved.flowGroups.find(item => item.id === group.id)!.versions[0].flow).toEqual(original.flow);
});

test('UXE05: wireframe selection groups retain Enter and Space editing while preview buttons still navigate', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  await page.goto(`/#project/${original.id}/wireframes`);
  const selection = page.getByTestId(`wire-element-${original.id}-nested-nested-link`);
  await expect(selection).toHaveAttribute('role', 'group');
  await expect(selection).toHaveAttribute('aria-keyshortcuts', 'Enter Space');
  await selection.focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('textbox', { name: '요소 내용', exact: true })).toHaveValue('중첩 도서 상세');
  const heading = page.getByTestId(`wire-element-${original.id}-nested-nested-title`);
  await heading.focus(); await page.keyboard.press('Space');
  await expect(page.getByRole('textbox', { name: '요소 내용', exact: true })).toHaveValue('깊은 계층의 추천 도서');
  await page.getByRole('button', { name: '미리보기', exact: true }).click();
  await expect(selection).not.toHaveAttribute('role', 'group');
  await page.getByRole('button', { name: '중첩 도서 상세', exact: true }).click();
  await expect(page.getByTestId('wireframe-preview')).toContainText('도서 상세 페이지');
  expect(await getProject(request, original.id)).toEqual(original);
});
