import { expect, test } from '@playwright/test';
import { getProject, seedNestedProject } from '../phase2-fixtures.js';

test('UXE01: wireframe panels collapse before the canvas shrinks, preserve edits and never mutate data on resize', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`/#project/${original.id}/wireframes`);
  // Also supports the legacy route until the workspace router has loaded.
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  const list = page.getByRole('complementary', { name: '화면 목록', exact: true });
  const inspector = page.getByRole('complementary', { name: '화면 속성', exact: true });
  await expect(list).toBeVisible(); await expect(inspector).toBeVisible();
  const selectedVersion = original.selectedWireframeVersionId;
  await page.getByTestId(`layer-${original.id}-nested-nested-title`).click();
  await page.getByRole('textbox', { name: '요소 내용', exact: true }).fill('폭이 바뀌어도 유지되는 제목');
  await expect.poll(async () => JSON.stringify((await getProject(request, original.id)).wireframes)).toContain('폭이 바뀌어도 유지되는 제목');
  const saved = await getProject(request, original.id);
  const mutations: string[] = [];
  page.on('request', req => { if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(req.method())) mutations.push(req.url()); });
  await page.setViewportSize({ width: 970, height: 760 });
  await expect(list).toBeHidden(); await expect(inspector).toBeVisible();
  await expect.poll(async () => (await page.locator('.wf-stage').boundingBox())!.width).toBeGreaterThanOrEqual(600);
  await expect(page.getByRole('textbox', { name: '요소 내용', exact: true })).toHaveValue('폭이 바뀌어도 유지되는 제목');
  await page.screenshot({ path: 'tests/artifacts/ux-wireframe-970.png', fullPage: true });
  await page.getByRole('button', { name: '화면 목록 표시', exact: true }).click();
  await expect(list).toBeVisible(); await expect(list).toHaveCSS('position', 'absolute');
  await page.getByRole('button', { name: '화면 목록 접기', exact: true }).press('Escape');
  await expect(page.getByRole('button', { name: '화면 목록 표시', exact: true })).toBeFocused();
  // CSS pixels equivalent to a 1440px window at 200% zoom. The actively opened inspector overlays.
  await page.getByRole('textbox', { name: '요소 내용', exact: true }).focus();
  await page.setViewportSize({ width: 720, height: 500 });
  await expect(inspector).toBeVisible(); await expect(inspector).toHaveCSS('position', 'absolute');
  await expect(page.getByRole('textbox', { name: '요소 내용', exact: true })).toBeFocused();
  await page.screenshot({ path: 'tests/artifacts/ux-wireframe-720-overlay.png', fullPage: true });
  await page.getByRole('button', { name: '화면 속성 접기', exact: true }).click();
  await page.getByRole('button', { name: '화면 속성 표시', exact: true }).click();
  await expect(inspector).toBeVisible(); await expect(inspector).toHaveCSS('position', 'absolute');
  await expect(page.getByRole('textbox', { name: '요소 내용', exact: true })).toHaveValue('폭이 바뀌어도 유지되는 제목');
  await page.getByRole('button', { name: '화면 속성 접기', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  const after = await getProject(request, original.id);
  expect(after).toEqual(saved); expect(after.selectedWireframeVersionId).toBe(selectedVersion); expect(mutations).toEqual([]);
});

