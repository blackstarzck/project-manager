import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { getProject } from '../phase2-fixtures.js';
import { seedPreviewProject } from '../phase7-fixtures.js';

test('VP01: preview groups and searches pages on the right while paging, zoom and real internal scrolling keep project data unchanged', async ({ page, request }) => {
  const original = await seedPreviewProject(request), mutations: string[] = [];
  await page.goto(`/#project/${original.id}`); await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  page.on('request', req => { if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(req.method())) mutations.push(req.url()); });
  await page.getByRole('button', { name: '미리보기', exact: true }).click();
  const list = page.getByRole('complementary', { name: '화면 목록', exact: true }), viewport = page.getByTestId('wireframe-viewport');
  await expect(list.getByRole('heading', { name: /도서 이용/ })).toBeVisible();
  await expect(list.getByRole('heading', { name: /회원 업무/ })).toBeVisible();
  const listBox = await list.boundingBox(), viewportBox = await viewport.boundingBox();
  expect(listBox!.x).toBeGreaterThan(viewportBox!.x + viewportBox!.width);
  await expect(page.getByRole('status', { name: '현재 화면 번호', exact: true })).toHaveText('1 / 4');
  await expect(page.getByRole('button', { name: '이전 화면', exact: true })).toBeDisabled();
  await page.screenshot({ path: 'tests/artifacts/phase7-preview-pages.png', fullPage: true });
  await expect.poll(async () => viewport.evaluate(element => element.scrollHeight - element.clientHeight)).toBeGreaterThan(200);
  const controlsY = (await page.getByRole('button', { name: '다음 화면', exact: true }).boundingBox())!.y;
  await viewport.evaluate(element => { element.scrollTop = 300; });
  await expect.poll(async () => viewport.evaluate(element => element.scrollTop)).toBe(300);
  expect((await page.getByRole('button', { name: '다음 화면', exact: true }).boundingBox())!.y).toBe(controlsY);
  await page.getByRole('textbox', { name: '화면 목록 검색', exact: true }).fill('회원 업무');
  await expect(list.locator('[data-testid^="screen-"]')).toHaveCount(1);
  await expect(list.getByTestId(`screen-${original.wireframes[2].id}`)).toBeVisible();
  await list.getByTestId(`screen-${original.wireframes[2].id}`).click();
  await expect(page.getByRole('status', { name: '현재 화면 번호', exact: true })).toHaveText('3 / 4');
  await page.getByRole('textbox', { name: '화면 목록 검색', exact: true }).fill('없는 검색어');
  await expect(list.getByText('검색 결과가 없습니다.', { exact: false })).toBeVisible();
  await expect(page.getByRole('status', { name: '현재 화면 번호', exact: true })).toHaveText('3 / 4');
  await page.getByRole('button', { name: '화면 검색 지우기', exact: true }).click();
  await page.getByRole('button', { name: '다음 화면', exact: true }).click();
  await expect(page.getByRole('status', { name: '현재 화면 번호', exact: true })).toHaveText('4 / 4');
  await expect(page.getByRole('button', { name: '다음 화면', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '이전 화면', exact: true }).click();
  const zoom = page.getByLabel('현재 화면 배율', { exact: true }), beforeZoom = await zoom.innerText();
  await page.getByRole('button', { name: '화면 확대', exact: true }).click();
  await expect(zoom).not.toHaveText(beforeZoom);
  await page.getByRole('button', { name: '화면에 맞추기', exact: true }).click();
  await expect(zoom).toHaveText(beforeZoom);
  const baselineDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'PNG', exact: true }).click();
  const baseline = await baselineDownload;
  await baseline.saveAs('tests/artifacts/phase7-preview-no-hint.png');
  await page.getByTestId(`wire-element-${original.wireframes[2].id}-generated-fixture-copy`).click();
  await expect(page.getByTestId(`wire-element-${original.wireframes[2].id}-generated-fixture-open`)).toHaveClass(/wf-interactive-hint/);
  await expect(page.getByTestId(`wire-element-${original.wireframes[2].id}-generated-fixture-open`)).toHaveCSS('outline-color', 'rgb(59, 130, 246)');
  await expect(page.getByTestId(`wire-element-${original.wireframes[2].id}-generated-fixture-open`)).toHaveCSS('outline-width', '2px');
  const hintedDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'PNG', exact: true }).click();
  const hinted = await hintedDownload;
  await hinted.saveAs('tests/artifacts/phase7-preview-during-hint.png');
  expect(await readFile((await hinted.path())!)).toEqual(await readFile((await baseline.path())!));
  expect(mutations).toEqual([]); expect(await getProject(request, original.id)).toEqual(original);
  await page.getByRole('button', { name: '직접 편집', exact: true }).click();
  await expect(page.getByRole('complementary', { name: '화면 속성', exact: true })).toBeVisible();
  await expect(page.getByRole('textbox', { name: '화면 이름', exact: true })).toHaveValue(original.wireframes[2].name);
});

test('VP02: preview regeneration sends only the currently displayed screen with both version IDs and waits for approval', async ({ page, request }) => {
  const original = await seedPreviewProject(request);
  await page.goto(`/#project/${original.id}`); await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  await page.getByRole('button', { name: '미리보기', exact: true }).click();
  await page.getByRole('button', { name: '다음 화면', exact: true }).click();
  const started = page.waitForRequest(req => req.method() === 'POST' && req.url().endsWith(`/api/projects/${original.id}/ai/runs`));
  await page.getByRole('button', { name: '페이지 다시 생성', exact: true }).click();
  expect((await started).postDataJSON()).toMatchObject({ artifact: 'wireframes', entityIds: [original.wireframes[1].id], flowVersionId: original.selectedFlowVersionId, wireframeVersionId: original.selectedWireframeVersionId });
  await page.getByRole('button', { name: '변경 제안 검토', exact: true }).click();
  expect(await getProject(request, original.id)).toEqual(original);
  await page.getByRole('button', { name: '선택 거절', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect(await getProject(request, original.id)).toEqual(original);
});

test('VP03: generation search groups pages and preserves hidden choices while submitting the exact reviewed scope', async ({ page, request }) => {
  const original = await seedPreviewProject(request), started: unknown[] = [];
  await page.goto(`/#project/${original.id}`); await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  page.on('request', req => { if (req.method() === 'POST' && req.url().endsWith(`/api/projects/${original.id}/ai/runs`)) started.push(req.postDataJSON()); });
  await page.getByRole('button', { name: '전체 화면 개선', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '와이어프레임 생성 대상 선택', exact: true });
  await expect(dialog.getByRole('heading', { name: /도서 이용/ })).toBeVisible();
  await dialog.getByRole('checkbox', { name: '대상 전체 선택', exact: true }).uncheck();
  await dialog.getByTestId(`wireframe-target-${original.wireframes[0].id}`).check();
  await dialog.getByRole('textbox', { name: '생성 대상 화면 검색', exact: true }).fill('회원 업무');
  await expect(dialog.getByRole('group', { name: '생성 대상 화면', exact: true }).getByRole('checkbox')).toHaveCount(1);
  await dialog.getByTestId(`wireframe-target-${original.wireframes[2].id}`).check();
  await expect(dialog.getByRole('status')).toContainText('2개 선택 / 4개');
  await dialog.getByRole('textbox', { name: '생성 대상 화면 검색', exact: true }).fill('없는 검색어');
  await expect(dialog.getByText('검색 결과가 없습니다. 기존 선택은 유지됩니다.', { exact: true })).toBeVisible();
  await expect(dialog.getByRole('status')).toContainText('2개 선택 / 4개');
  await dialog.getByRole('textbox', { name: '생성 대상 화면 검색', exact: true }).fill('');
  await expect(dialog.getByTestId(`wireframe-target-${original.wireframes[0].id}`)).toBeChecked();
  await expect(dialog.getByTestId(`wireframe-target-${original.wireframes[1].id}`)).not.toBeChecked();
  await expect(dialog.getByTestId(`wireframe-target-${original.wireframes[2].id}`)).toBeChecked();
  await expect(dialog.getByTestId(`wireframe-target-${original.wireframes[3].id}`)).not.toBeChecked();
  await dialog.getByRole('checkbox', { name: '새 화면 버전으로 만들기', exact: true }).uncheck();
  await page.screenshot({ path: 'tests/artifacts/phase7-generation-sections.png', fullPage: true });
  expect(started).toEqual([]);
  await dialog.getByRole('button', { name: '선택한 화면 생성 요청', exact: true }).click();
  await page.getByRole('button', { name: '변경 제안 검토', exact: true }).click();
  expect(started).toHaveLength(1);
  expect(started[0]).toMatchObject({ artifact: 'wireframes', wireframeGenerationMode: 'edit', entityIds: [original.wireframes[0].id, original.wireframes[2].id], flowVersionId: original.selectedFlowVersionId, wireframeVersionId: original.selectedWireframeVersionId });
  expect(await getProject(request, original.id)).toEqual(original);
  await page.getByRole('button', { name: '선택 거절', exact: true }).click();
  expect(await getProject(request, original.id)).toEqual(original);
});
