import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';
import { API, saveArtifact } from '../fixtures.js';
import { flattenElements, getProject, seedNestedProject } from '../phase2-fixtures.js';

test('DV01: tablet is a persistent device and exports a real 768 by 1024 minimum canvas', async ({ page, request, context }) => {
  const project = await seedNestedProject(request);
  await page.goto(`/#project/${project.id}`);
  await page.getByRole('button', { name: '프로젝트 설정', exact: true }).click();
  const settings = page.getByRole('dialog', { name: '프로젝트 설정', exact: true });
  await settings.getByRole('checkbox', { name: '태블릿', exact: true }).check();
  await settings.getByRole('checkbox', { name: '모바일', exact: true }).check();
  await settings.getByRole('button', { name: '설정 저장', exact: true }).click();
  await expect(settings).toHaveCount(0);
  expect((await getProject(request, project.id)).settings.devices).toEqual(['desktop', 'tablet', 'mobile']);
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  await page.getByRole('button', { name: '화면 추가', exact: true }).first().click();
  const create = page.getByRole('dialog', { name: '새 화면 만들기', exact: true });
  await create.getByRole('textbox', { name: '새 화면 이름', exact: true }).fill('태블릿 전용 예약 현황');
  await create.getByRole('combobox', { name: /^기기/ }).selectOption('tablet');
  await create.getByRole('button', { name: '화면 만들기', exact: true }).click();
  await expect.poll(async () => (await getProject(request, project.id)).wireframes.length).toBe(3);
  const current = await getProject(request, project.id);
  const tablet = current.wireframes.find(screen => screen.name === '태블릿 전용 예약 현황')!;
  expect(tablet.device).toBe('tablet');
  expect(current.wireframes.slice(0, 2)).toEqual(project.wireframes);
  await page.reload();
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  await page.getByTestId(`screen-${tablet.id}`).click();
  await expect(page.getByRole('button', { name: 'Tablet', exact: true })).toHaveClass(/selected/);
  const dimensions = await page.getByTestId('wireframe-preview').evaluate(element => ({ width: (element as HTMLElement).offsetWidth, height: (element as HTMLElement).offsetHeight }));
  expect(dimensions.width).toBe(768);
  expect(dimensions.height).toBeGreaterThanOrEqual(1024);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'PNG', exact: true }).click();
  await (await download).saveAs('tests/artifacts/phase4-tablet.png');
  const png = await readFile('tests/artifacts/phase4-tablet.png');
  expect(png.subarray(0, 8).toString('hex')).toBe('89504e470d0a1a0a');
  expect(png.readUInt32BE(16)).toBe(1536);
  expect(png.readUInt32BE(20)).toBeGreaterThanOrEqual(2048);
  const response = await request.get(`${API}/projects/${project.id}/export?format=html`);
  expect(response.ok()).toBeTruthy();
  const offline = await context.newPage();
  await offline.setContent(await response.text());
  await offline.locator('body > header nav').getByRole('link', { name: tablet.name, exact: true }).click();
  const exported = await offline.locator('.screen.active').boundingBox();
  expect(exported!.width).toBe(768);
  expect(exported!.height).toBeGreaterThanOrEqual(1024);
  for (const heading of await offline.getByRole('heading', { name: tablet.name, exact: true }).all()) await expect(heading).toBeVisible();
  await expect(offline.getByRole('heading', { name: tablet.name, exact: true })).toHaveCount(2);
  await offline.close();
});

test('NV01: common navigation copies selected regions/screens with fresh IDs, retains body and can be undone', async ({ page, request, context }) => {
  let project = await seedNestedProject(request);
  const source = structuredClone(project.wireframes[0]);
  source.elements[0].children!.push({ id: `${project.id}-header-external-modal`, type: 'button', text: '외부 모달 연결', targetScreenId: null, action: 'openModal', targetElementId: `${project.id}-nested-modal` });
  const untouched = { ...structuredClone(project.wireframes[1]), id: `${project.id}-unselected-screen`, name: '별도로 보존할 화면', flowNodeId: null, revision: 0 };
  project = await saveArtifact(request, project, 'wireframes', [source, project.wireframes[1], untouched]);
  const originalTarget = project.wireframes[1];
  const originalBody = flattenElements(originalTarget.elements).find(element => element.id === `${project.id}-nested-detail-body`)!;
  const originalSidebar = flattenElements(originalTarget.elements).find(element => element.type === 'sidebar')!;
  await page.goto(`/#project/${project.id}`);
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  await page.getByRole('button', { name: '공통 내비게이션 적용', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '공통 내비게이션 적용', exact: true });
  await dialog.getByRole('checkbox', { name: '사이드바 적용', exact: true }).uncheck();
  await dialog.getByRole('checkbox', { name: '푸터 적용', exact: true }).uncheck();
  await dialog.getByRole('checkbox', { name: '공통 영역 대상 전체 선택', exact: true }).uncheck();
  await expect(dialog.getByRole('button', { name: '선택한 화면에 공통 영역 적용', exact: true })).toBeDisabled();
  await dialog.getByRole('checkbox', { name: '도서 상세 공통 영역 적용', exact: true }).check();
  await page.screenshot({ path: 'tests/artifacts/phase4-common-navigation.png', fullPage: true });
  await dialog.getByRole('button', { name: '선택한 화면에 공통 영역 적용', exact: true }).click();
  await expect.poll(async () => (await getProject(request, project.id)).wireframes[1].revision).toBeGreaterThan(originalTarget.revision);
  const result = await getProject(request, project.id);
  expect(result.wireframes[0]).toEqual(project.wireframes[0]);
  expect(result.wireframes[2]).toEqual(project.wireframes[2]);
  const targetElements = flattenElements(result.wireframes[1].elements);
  expect(targetElements.find(element => element.id === originalBody.id)).toEqual(originalBody);
  expect(targetElements.find(element => element.id === originalSidebar.id)).toEqual(originalSidebar);
  const copiedHeader = targetElements.find(element => element.type === 'header')!;
  const originalIds = new Set(flattenElements(project.wireframes[0].elements).map(element => element.id));
  for (const element of flattenElements([copiedHeader])) expect(originalIds.has(element.id)).toBeFalsy();
  expect(new Set(targetElements.map(element => element.id)).size).toBe(targetElements.length);
  const externalModal = targetElements.find(element => element.text === '외부 모달 연결')!;
  expect(externalModal.targetElementId).toBeNull();
  expect(externalModal.action).not.toBe('openModal');
  const response = await request.get(`${API}/projects/${project.id}/export?format=html`);
  expect(response.ok()).toBeTruthy();
  const offline = await context.newPage();
  await offline.setContent(await response.text());
  await offline.locator('body > header nav').getByRole('link', { name: '도서 상세', exact: true }).click();
  await expect(offline.locator('.screen.active').getByRole('heading', { name: '우리 동네 도서관', exact: true })).toBeVisible();
  await expect(offline.locator('.screen.active').getByRole('heading', { name: '도서 상세 페이지', exact: true })).toBeVisible();
  await offline.close();
  await page.getByTestId(`screen-${originalTarget.id}`).click();
  await page.getByRole('button', { name: '화면 편집 실행 취소', exact: true }).click();
  await expect.poll(async () => (await getProject(request, project.id)).wireframes[1].elements).toEqual(originalTarget.elements);
  expect((await getProject(request, project.id)).wireframes[2]).toEqual(project.wireframes[2]);
});

test('NV02: copying a missing common region into a full sibling list is rejected before creating an unsavable draft', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  const fullScreen = { ...original.wireframes[1], name: '요소 한도 화면', elements: Array.from({ length: 100 }, (_, index) => ({ id: `${original.id}-full-${index}`, type: 'text' as const, text: `기존 본문 ${index}`, targetScreenId: null })) };
  const project = await saveArtifact(request, original, 'wireframes', [original.wireframes[0], fullScreen]);
  await page.goto(`/#project/${project.id}`);
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  await page.getByRole('button', { name: '공통 내비게이션 적용', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '공통 내비게이션 적용', exact: true });
  await dialog.getByRole('checkbox', { name: '사이드바 적용', exact: true }).uncheck();
  await dialog.getByRole('checkbox', { name: '푸터 적용', exact: true }).uncheck();
  await dialog.getByRole('button', { name: '선택한 화면에 공통 영역 적용', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: /100/ })).toBeVisible();
  await expect(page.getByRole('status').filter({ hasText: '모든 변경 저장됨' })).toBeVisible();
  expect(await getProject(request, project.id)).toEqual(project);
  await page.getByTestId(`screen-${project.wireframes[1].id}`).click();
  await expect(page.getByTestId(`layer-${project.id}-full-99`)).toBeVisible();
  await expect(page.getByRole('button', { name: '화면 편집 실행 취소', exact: true })).toBeDisabled();
});
