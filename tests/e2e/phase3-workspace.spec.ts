import { expect, test } from '@playwright/test';
import { saveArtifact } from '../fixtures.js';
import { addFlowVersion, getProject, seedNestedProject, selectFlowVersion } from '../phase2-fixtures.js';

test('W01: wireframe version selector flushes nested edits, resets history and persists the selected context', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  let project = await addFlowVersion(request, original, { copy: true, name: '독립 화면 버전' });
  const copyId = project.selectedFlowVersionId!;
  project = await selectFlowVersion(request, project, original.selectedFlowVersionId!);
  await page.goto(`/#project/${project.id}`);
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  const selector = page.getByRole('combobox', { name: '와이어프레임 플로우 버전 선택', exact: true });
  await expect(selector).toHaveValue(original.selectedFlowVersionId!);
  await page.getByTestId(`layer-${project.id}-nested-nested-title`).click();
  await page.getByRole('textbox', { name: '요소 내용', exact: true }).fill('전환 직전에 입력한 깊은 화면 제목');
  await selector.selectOption(copyId);
  await expect(selector).toHaveValue(copyId);
  await expect(page.getByRole('tab', { name: '와이어프레임', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByRole('button', { name: '화면 편집 실행 취소', exact: true })).toBeDisabled();
  let current = await getProject(request, project.id);
  expect(current.wireframes).toEqual(original.wireframes);
  expect(JSON.stringify(current.flowGroups[0].versions.find(version => version.id === original.selectedFlowVersionId)!.wireframes)).toContain('전환 직전에 입력한 깊은 화면 제목');
  await page.reload();
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  await expect(selector).toHaveValue(copyId);
  await selector.selectOption(original.selectedFlowVersionId!);
  await expect(page.getByTestId(`wire-element-${project.id}-nested-nested-title`)).toContainText('전환 직전에 입력한 깊은 화면 제목');
  await page.screenshot({ path: 'tests/artifacts/phase3-wireframe-context.png', fullPage: true });
});

test('W02: failed save from wireframe selector retains the current version and editable draft until retry', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  let project = await addFlowVersion(request, original, { copy: true });
  const copyId = project.selectedFlowVersionId!;
  project = await selectFlowVersion(request, project, original.selectedFlowVersionId!);
  await page.goto(`/#project/${project.id}`);
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  const selector = page.getByRole('combobox', { name: '와이어프레임 플로우 버전 선택', exact: true });
  const route = `**/api/projects/${project.id}/artifacts/wireframes`;
  await page.route(route, intercepted => intercepted.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 'QA_SAVE_FAILED', message: '검수용 저장 실패' }) }));
  await page.getByTestId(`layer-${project.id}-nested-nested-title`).click();
  await page.getByRole('textbox', { name: '요소 내용', exact: true }).fill('저장 실패에도 남아야 하는 화면 초안');
  await selector.selectOption(copyId);
  await expect(page.getByRole('button', { name: '저장 재시도', exact: true })).toBeVisible();
  await expect(selector).toHaveValue(original.selectedFlowVersionId!);
  await expect(page.getByRole('textbox', { name: '요소 내용', exact: true })).toHaveValue('저장 실패에도 남아야 하는 화면 초안');
  expect((await getProject(request, project.id)).selectedFlowVersionId).toBe(original.selectedFlowVersionId);
  await page.unroute(route);
  await selector.selectOption(copyId);
  await expect(selector).toHaveValue(copyId);
  const saved = await getProject(request, project.id);
  expect(saved.wireframes).toEqual(original.wireframes);
  expect(JSON.stringify(saved.flowGroups[0].versions.find(version => version.id === original.selectedFlowVersionId)!.wireframes)).toContain('저장 실패에도 남아야 하는 화면 초안');
});

test('G06: toolbar explicitly generates a new version and approved result opens without misleading origin-switch action', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  await page.goto(`/#project/${original.id}`);
  await page.getByRole('tab', { name: '유저플로우', exact: true }).click();
  await page.getByRole('button', { name: 'AI 생성', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'AI 플로우 생성', exact: true });
  await expect(dialog.getByRole('radio', { name: '현재 플로우의 AI 수정본', exact: true })).toBeChecked();
  await dialog.getByRole('textbox', { name: '플로우 AI 요청 내용', exact: true }).fill('[QA_NEW_VERSION_CONTEXT] [QA_FRESH_FLOW] 다음 여정');
  await page.screenshot({ path: 'tests/artifacts/phase3-flow-generation.png', fullPage: true });
  const started = page.waitForRequest(req => req.method() === 'POST' && req.url().endsWith(`/api/projects/${original.id}/ai/runs`));
  await dialog.getByRole('button', { name: 'AI 플로우 생성 요청', exact: true }).click();
  expect((await started).postDataJSON().flowGenerationMode).toBe('new-version');
  await page.getByRole('button', { name: '변경 제안 검토', exact: true }).click();
  expect(await getProject(request, original.id)).toEqual(original);
  await page.getByRole('button', { name: '선택 승인', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const result = await getProject(request, original.id);
  expect(result.selectedFlowVersionId).not.toBe(original.selectedFlowVersionId);
  expect(result.flowGroups[0].versions[0]).toEqual(original.flowGroups[0].versions[0]);
  expect(result.wireframes).toEqual([]);
  await expect(page.getByRole('button', { name: '원래 플로우 버전으로 전환', exact: true })).toHaveCount(0);
  await page.getByRole('tab', { name: '와이어프레임', exact: true }).click();
  await page.getByRole('combobox', { name: '와이어프레임 플로우 버전 선택', exact: true }).selectOption(original.selectedFlowVersionId!);
  await expect(page.getByTestId(`screen-${original.wireframes[0].id}`)).toBeVisible();
  await page.getByRole('button', { name: '생성된 플로우 보기', exact: true }).click();
  await expect(page.getByRole('tab', { name: '유저플로우', exact: true })).toHaveAttribute('aria-selected', 'true');
  expect((await getProject(request, original.id)).selectedFlowVersionId).toBe(result.selectedFlowVersionId);
  await page.screenshot({ path: 'tests/artifacts/phase3-ai-new-version.png', fullPage: true });
});

test('G07: conflict regeneration retains original generation mode and manual content until a new approval', async ({ page, request }) => {
  const original = await seedNestedProject(request);
  await page.goto(`/#project/${original.id}`);
  await page.getByRole('tab', { name: '유저플로우', exact: true }).click();
  await page.getByRole('button', { name: 'AI 도우미 열기', exact: true }).click();
  const mode = page.getByRole('combobox', { name: '플로우 생성 방식', exact: true });
  await expect(mode).toHaveValue('edit');
  await mode.selectOption('new-group');
  await page.getByRole('textbox', { name: 'AI 요청', exact: true }).fill('[QA_NEW_GROUP_CONTEXT] [QA_FRESH_FLOW] 새 관리 흐름');
  await page.getByRole('button', { name: 'AI 생성 요청', exact: true }).click();
  await expect(page.getByRole('button', { name: '변경 제안 검토', exact: true })).toBeVisible();
  // An independent server edit forces the approval check to see a real source revision conflict.
  const manual = await saveArtifact(request, original, 'flow', { ...original.flow, nodes: original.flow.nodes.map((node, index) => index === 1 ? { ...node, label: '승인 전에 직접 수정한 검색' } : node) });
  await page.getByRole('button', { name: '변경 제안 검토', exact: true }).click();
  const conflicting = page.waitForResponse(res => res.request().method() === 'POST' && res.url().includes('/proposals/') && res.url().endsWith('/resolve'));
  await page.getByRole('button', { name: '선택 승인', exact: true }).click();
  expect((await conflicting).status()).toBe(409);
  await page.getByRole('dialog').getByRole('button', { name: '닫기', exact: true }).click();
  await page.reload();
  await page.getByRole('tab', { name: '유저플로우', exact: true }).click();
  if (!(await page.getByRole('textbox', { name: 'AI 요청', exact: true }).isVisible())) await page.getByRole('button', { name: 'AI 도우미 열기', exact: true }).click();
  // Composer state differs now; retry must use the saved run's mode.
  await page.getByRole('combobox', { name: '플로우 생성 방식', exact: true }).selectOption('edit');
  const retried = page.waitForRequest(req => req.method() === 'POST' && req.url().endsWith(`/api/projects/${original.id}/ai/runs`));
  await page.getByRole('button', { name: '현재 문서로 다시 생성', exact: true }).click();
  const payload = (await retried).postDataJSON();
  expect(payload.flowGenerationMode).toBe('new-group');
  expect(payload.flowVersionId).toBe(original.selectedFlowVersionId);
  expect(payload.entityIds).toEqual([]);
  await page.getByRole('button', { name: '변경 제안 검토', exact: true }).click();
  expect(await getProject(request, original.id)).toEqual(manual);
  await page.getByRole('button', { name: '선택 승인', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const result = await getProject(request, original.id);
  expect(result.flowGroups).toHaveLength(2);
  expect(result.flowGroups[0]).toEqual(manual.flowGroups[0]);
});
